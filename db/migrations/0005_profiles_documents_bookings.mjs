/* Freelancer pricing and weekly availability, verification documents, and bookings.

   wl_users (the freelancer profile lives on the user row):
   - pricing_type HOURLY | FIXED_PACKAGE | PER_EVENT, price_amount, price_unit_label
     (replaces the old hourly `rate`, which is copied into price_amount)
   - travel_radius_km, slot_duration_minutes, available_for_urgent, service_perks, subcategories
   - weekly_availability: {"MON": [{"start": "09:00", "end": "17:00"}], ...}
     (replaces `availability` {days, times}; existing values are converted:
      morning 08–12, afternoon 12–17, evening 17–21)
   - onboarding_completed_at
   - verification status stays in ver_status: none | pending | verified | rejected

   wl_verification_documents: one row per uploaded document. The file itself is kept in `data`
   only until an admin approves or rejects it, then cleared (as the privacy policy promises).
   Pending documents from the old single-document table wl_documents are carried over.

   wl_bookings: a client books a freelancer for a date and time. An exclusion constraint stops
   two active bookings for the same freelancer from overlapping, even under concurrent requests. */
import { sql } from 'kysely';

const UP = [
  // ---- freelancer profile ----
  `ALTER TABLE wl_users
     ADD COLUMN pricing_type text NOT NULL DEFAULT 'HOURLY' CHECK (pricing_type IN ('HOURLY', 'FIXED_PACKAGE', 'PER_EVENT')),
     ADD COLUMN price_amount numeric(12, 2) NOT NULL DEFAULT 0 CHECK (price_amount >= 0),
     ADD COLUMN price_unit_label text,
     ADD COLUMN travel_radius_km integer NOT NULL DEFAULT 15 CHECK (travel_radius_km BETWEEN 0 AND 300),
     ADD COLUMN weekly_availability jsonb NOT NULL DEFAULT '{}'::jsonb,
     ADD COLUMN slot_duration_minutes integer NOT NULL DEFAULT 60 CHECK (slot_duration_minutes BETWEEN 15 AND 480),
     ADD COLUMN available_for_urgent boolean NOT NULL DEFAULT false,
     ADD COLUMN service_perks jsonb NOT NULL DEFAULT '[]'::jsonb,
     ADD COLUMN subcategories jsonb NOT NULL DEFAULT '[]'::jsonb,
     ADD COLUMN onboarding_completed_at timestamptz`,
  `UPDATE wl_users SET price_amount = rate WHERE rate > 0`,
  // {days:[mon..], times:[morning..]} → {"MON":[{start,end},...]}
  `UPDATE wl_users u SET weekly_availability = COALESCE((
     SELECT jsonb_object_agg(upper(d.day), w.windows)
     FROM jsonb_array_elements_text(u.availability -> 'days') AS d(day)
     CROSS JOIN LATERAL (
       SELECT jsonb_agg(jsonb_build_object('start', t.s, 'end', t.e) ORDER BY t.s) AS windows
       FROM (VALUES ('morning', '08:00', '12:00'), ('afternoon', '12:00', '17:00'), ('evening', '17:00', '21:00')) AS t(k, s, e)
       WHERE (u.availability -> 'times') ? t.k
     ) AS w
     WHERE w.windows IS NOT NULL
   ), '{}'::jsonb)`,
  // Anyone who already filled in a freelancer profile counts as onboarded.
  `UPDATE wl_users SET onboarding_completed_at = now() WHERE is_freelancer AND specialty <> ''`,
  `ALTER TABLE wl_users DROP COLUMN rate, DROP COLUMN availability`,

  // ---- verification documents ----
  `CREATE TABLE wl_verification_documents (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    document_type text NOT NULL CHECK (document_type IN ('GOVERNMENT_ID', 'DRIVERS_LICENSE', 'BACKGROUND_CHECK')),
    file_name     text NOT NULL DEFAULT '',
    mime          text NOT NULL DEFAULT '',
    data          bytea,  -- cleared once reviewed
    status        text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    reason        text,
    uploaded_at   timestamptz NOT NULL DEFAULT now(),
    reviewed_at   timestamptz,
    reviewed_by   integer REFERENCES wl_users (id) ON DELETE SET NULL
  )`,
  `CREATE INDEX wl_verification_documents_user ON wl_verification_documents (user_id, document_type, uploaded_at)`,
  `CREATE INDEX wl_verification_documents_pending ON wl_verification_documents (uploaded_at) WHERE status = 'PENDING'`,
  `INSERT INTO wl_verification_documents (user_id, document_type, file_name, mime, data, status, uploaded_at)
     SELECT d.user_id,
            CASE WHEN u.ver_doc_type ILIKE 'driv%' THEN 'DRIVERS_LICENSE' ELSE 'GOVERNMENT_ID' END,
            coalesce(u.ver_file_name, ''), d.mime, d.data, 'PENDING', coalesce(u.ver_submitted, now())
     FROM wl_documents d JOIN wl_users u ON u.id = d.user_id
     WHERE u.ver_status = 'pending'`,
  `DROP TABLE wl_documents`,

  // ---- bookings ----
  `CREATE EXTENSION IF NOT EXISTS btree_gist`,
  `CREATE TABLE wl_bookings (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id           integer NOT NULL REFERENCES wl_users (id) ON DELETE RESTRICT,
    freelancer_id       integer NOT NULL REFERENCES wl_users (id) ON DELETE RESTRICT,
    service_category_id text REFERENCES wl_categories (id) ON DELETE SET NULL,
    booking_date        date NOT NULL,
    start_time          time NOT NULL,
    end_time            time NOT NULL,
    duration_minutes    integer NOT NULL CHECK (duration_minutes > 0),
    total_price         numeric(12, 2) NOT NULL CHECK (total_price >= 0),
    address             text NOT NULL,
    notes               text,
    status              text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('AWAITING_PAYMENT', 'PENDING', 'CONFIRMED', 'COMPLETED', 'CANCELLED')),
    cancelled_by        integer REFERENCES wl_users (id) ON DELETE SET NULL,
    cancel_reason       text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CHECK (end_time > start_time),
    CONSTRAINT wl_bookings_no_overlap EXCLUDE USING gist (
      freelancer_id WITH =,
      tsrange(booking_date + start_time, booking_date + end_time) WITH &&
    ) WHERE (status IN ('AWAITING_PAYMENT', 'PENDING', 'CONFIRMED'))
  )`,
  `CREATE INDEX wl_bookings_freelancer_date ON wl_bookings (freelancer_id, booking_date)`,
  `CREATE INDEX wl_bookings_client ON wl_bookings (client_id)`,
  `ALTER TABLE wl_payments ADD COLUMN booking_id integer REFERENCES wl_bookings (id) ON DELETE RESTRICT`,
  `CREATE INDEX wl_payments_booking ON wl_payments (booking_id)`,
];

const DOWN = [
  'DROP INDEX IF EXISTS wl_payments_booking',
  'ALTER TABLE wl_payments DROP COLUMN IF EXISTS booking_id',
  'DROP TABLE IF EXISTS wl_bookings',
  `CREATE TABLE wl_documents (
    user_id integer PRIMARY KEY REFERENCES wl_users (id) ON DELETE CASCADE,
    mime    text NOT NULL,
    data    bytea NOT NULL
  )`,
  // Keep the newest pending document per user.
  `INSERT INTO wl_documents (user_id, mime, data)
     SELECT DISTINCT ON (user_id) user_id, mime, data FROM wl_verification_documents
     WHERE status = 'PENDING' AND data IS NOT NULL ORDER BY user_id, uploaded_at DESC`,
  'DROP TABLE IF EXISTS wl_verification_documents',
  `ALTER TABLE wl_users
     ADD COLUMN rate numeric(12, 2) NOT NULL DEFAULT 0,
     ADD COLUMN availability jsonb NOT NULL DEFAULT '{"days": [], "times": []}'::jsonb`,
  `UPDATE wl_users SET rate = price_amount WHERE pricing_type = 'HOURLY'`,
  // Back to {days, times}: a day counts if it has any window; a time of day counts if any window overlaps it.
  `UPDATE wl_users u SET availability = jsonb_build_object(
     'days', coalesce((SELECT jsonb_agg(lower(k) ORDER BY array_position(ARRAY['MON','TUE','WED','THU','FRI','SAT','SUN'], k))
                       FROM jsonb_object_keys(u.weekly_availability) AS k WHERE jsonb_array_length(u.weekly_availability -> k) > 0), '[]'::jsonb),
     'times', coalesce((SELECT jsonb_agg(t.k ORDER BY t.s) FROM (VALUES ('morning', '08:00', '12:00'), ('afternoon', '12:00', '17:00'), ('evening', '17:00', '21:00')) AS t(k, s, e)
                        WHERE EXISTS (SELECT 1 FROM jsonb_each(u.weekly_availability) AS day(k, v), jsonb_array_elements(day.v) AS w
                                      WHERE w ->> 'start' < t.e AND w ->> 'end' > t.s)), '[]'::jsonb))`,
  `ALTER TABLE wl_users
     DROP COLUMN pricing_type, DROP COLUMN price_amount, DROP COLUMN price_unit_label, DROP COLUMN travel_radius_km,
     DROP COLUMN weekly_availability, DROP COLUMN slot_duration_minutes, DROP COLUMN available_for_urgent,
     DROP COLUMN service_perks, DROP COLUMN subcategories, DROP COLUMN onboarding_completed_at`,
];

const run = async (db, statements) => { for (const s of statements) await sql.raw(s).execute(db); };

export const up = db => run(db, UP);
export const down = db => run(db, DOWN);
