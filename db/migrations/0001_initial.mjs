/* Initial PostgreSQL schema for Worklay, written as plain SQL.
   Money is numeric(12,2), times are timestamptz, flags are boolean and lists are jsonb.
   Financial records (orders, payments, payouts) use ON DELETE RESTRICT so they can't vanish
   when a user or listing is deleted; everything else cascades or is set to NULL.
   Ids are "generated by default" identities so the SQLite import can keep the old ids.
   The migrator runs each migration inside a transaction. */
import { sql } from 'kysely';

const UP = [
  `CREATE TABLE wl_users (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 text NOT NULL,
    email                text NOT NULL UNIQUE,
    pw_hash              text NOT NULL DEFAULT '',  -- empty for Google-only accounts
    google_id            text,
    title                text NOT NULL DEFAULT '',
    country              text NOT NULL DEFAULT '',
    city                 text NOT NULL DEFAULT '',
    area                 text NOT NULL DEFAULT '',
    bio                  text,
    skills               jsonb NOT NULL DEFAULT '[]'::jsonb,
    is_freelancer        boolean NOT NULL DEFAULT false,
    category             text NOT NULL DEFAULT '',
    rate                 numeric(12, 2) NOT NULL DEFAULT 0,
    role                 text NOT NULL DEFAULT 'user',
    color                text NOT NULL DEFAULT '#3858FF',
    balance              numeric(12, 2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
    ver_status           text NOT NULL DEFAULT 'none',
    ver_doc_type         text,
    ver_file             text,
    ver_file_name        text,
    ver_submitted        timestamptz,
    ver_reason           text,
    stripe_account_id    text,
    stripe_payouts_ready boolean NOT NULL DEFAULT false,
    created_at           timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE UNIQUE INDEX wl_users_google_id ON wl_users (google_id) WHERE google_id IS NOT NULL`,
  `CREATE UNIQUE INDEX wl_users_stripe_account ON wl_users (stripe_account_id) WHERE stripe_account_id IS NOT NULL`,

  `CREATE TABLE wl_sessions (
    token_hash text PRIMARY KEY,
    user_id    integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL
  )`,
  `CREATE INDEX wl_sessions_user ON wl_sessions (user_id)`,

  `CREATE TABLE wl_documents (
    user_id integer PRIMARY KEY REFERENCES wl_users (id) ON DELETE CASCADE,
    mime    text NOT NULL,
    data    bytea NOT NULL
  )`,

  `CREATE TABLE wl_services (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id   integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    title       text NOT NULL,
    category    text NOT NULL,
    emoji       text NOT NULL DEFAULT '💼',
    color       text NOT NULL DEFAULT '#dfe6ff',
    description text NOT NULL,
    packages    jsonb NOT NULL DEFAULT '[]'::jsonb,
    created_at  timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX wl_services_seller ON wl_services (seller_id)`,

  `CREATE TABLE wl_projects (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id       integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    title          text NOT NULL,
    category       text NOT NULL,
    description    text NOT NULL,
    budget_min     numeric(12, 2) NOT NULL,
    budget_max     numeric(12, 2) NOT NULL,
    deadline       text NOT NULL,
    skills         jsonb NOT NULL DEFAULT '[]'::jsonb,
    city           text NOT NULL DEFAULT '',
    area           text NOT NULL DEFAULT '',
    remote         boolean NOT NULL DEFAULT false,
    status         text NOT NULL DEFAULT 'open',
    awarded_to     integer REFERENCES wl_users (id) ON DELETE SET NULL,
    awarded_amount numeric(12, 2),
    created_at     timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX wl_projects_owner ON wl_projects (owner_id)`,
  `CREATE INDEX wl_projects_awarded_to ON wl_projects (awarded_to)`,

  `CREATE TABLE wl_proposals (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id integer NOT NULL REFERENCES wl_projects (id) ON DELETE CASCADE,
    seller_id  integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    amount     numeric(12, 2) NOT NULL,
    days       integer NOT NULL,
    cover      text NOT NULL,
    status     text NOT NULL DEFAULT 'pending',
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT wl_proposals_project_seller UNIQUE (project_id, seller_id)
  )`,
  `CREATE INDEX wl_proposals_seller ON wl_proposals (seller_id)`,

  `CREATE TABLE wl_orders (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id   integer NOT NULL REFERENCES wl_services (id) ON DELETE RESTRICT,
    pkg          integer NOT NULL,
    buyer_id     integer NOT NULL REFERENCES wl_users (id) ON DELETE RESTRICT,
    seller_id    integer NOT NULL REFERENCES wl_users (id) ON DELETE RESTRICT,
    price        numeric(12, 2) NOT NULL,
    requirements text,
    status       text NOT NULL DEFAULT 'in_queue',
    created_at   timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX wl_orders_buyer ON wl_orders (buyer_id)`,
  `CREATE INDEX wl_orders_seller_status ON wl_orders (seller_id, status)`,
  `CREATE INDEX wl_orders_service ON wl_orders (service_id)`,

  `CREATE TABLE wl_reviews (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_user integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    from_user   integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    service_id  integer REFERENCES wl_services (id) ON DELETE SET NULL,
    order_id    integer REFERENCES wl_orders (id) ON DELETE SET NULL,
    project_id  integer REFERENCES wl_projects (id) ON DELETE SET NULL,
    rating      integer NOT NULL,
    text        text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX wl_reviews_target ON wl_reviews (target_user)`,

  `CREATE TABLE wl_messages (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_id    integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    to_id      integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    text       text NOT NULL,
    is_read    boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX wl_messages_from ON wl_messages (from_id)`,
  `CREATE INDEX wl_messages_to ON wl_messages (to_id)`,

  `CREATE TABLE wl_notifications (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    type       text NOT NULL,
    text       text NOT NULL,
    link       text NOT NULL DEFAULT '',
    is_read    boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX wl_notifications_user ON wl_notifications (user_id, id)`,

  `CREATE TABLE wl_wishlist (
    user_id integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    kind    text NOT NULL,     -- 'service' or 'project'; item_id points into that table
    item_id integer NOT NULL,
    CONSTRAINT wl_wishlist_pk PRIMARY KEY (user_id, kind, item_id)
  )`,

  `CREATE TABLE wl_follows (
    follower integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    followee integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    CONSTRAINT wl_follows_pk PRIMARY KEY (follower, followee)
  )`,

  `CREATE TABLE wl_payouts (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer NOT NULL REFERENCES wl_users (id) ON DELETE RESTRICT,
    amount     numeric(12, 2) NOT NULL,
    method     text NOT NULL,
    details    text NOT NULL,
    status     text NOT NULL DEFAULT 'pending',
    created_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX wl_payouts_user ON wl_payouts (user_id)`,

  `CREATE TABLE wl_payments (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind                text NOT NULL,  -- 'order' or 'project'
    order_id            integer REFERENCES wl_orders (id) ON DELETE RESTRICT,
    project_id          integer REFERENCES wl_projects (id) ON DELETE RESTRICT,
    proposal_id         integer REFERENCES wl_proposals (id) ON DELETE SET NULL,
    buyer_id            integer NOT NULL REFERENCES wl_users (id) ON DELETE RESTRICT,
    seller_id           integer NOT NULL REFERENCES wl_users (id) ON DELETE RESTRICT,
    amount              numeric(12, 2) NOT NULL,
    fee                 numeric(12, 2) NOT NULL,
    status              text NOT NULL DEFAULT 'pending',
    checkout_session_id text UNIQUE,
    payment_intent_id   text,
    transfer_id         text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    paid_at             timestamptz,
    released_at         timestamptz
  )`,
  `CREATE INDEX wl_payments_seller_status ON wl_payments (seller_id, status)`,
  `CREATE INDEX wl_payments_buyer ON wl_payments (buyer_id)`,
  `CREATE INDEX wl_payments_order ON wl_payments (order_id)`,
  `CREATE INDEX wl_payments_project ON wl_payments (project_id)`,

  `CREATE TABLE wl_contacts (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL,
    email      text NOT NULL,
    message    text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
  )`,

  `CREATE TABLE wl_posts (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      text NOT NULL,
    emoji      text NOT NULL DEFAULT '📝',
    color      text NOT NULL DEFAULT '#eef1ff',
    excerpt    text NOT NULL,
    body       text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
  )`,
];

// Reverse dependency order.
const DOWN = [
  'DROP TABLE IF EXISTS wl_posts',
  'DROP TABLE IF EXISTS wl_contacts',
  'DROP TABLE IF EXISTS wl_payments',
  'DROP TABLE IF EXISTS wl_payouts',
  'DROP TABLE IF EXISTS wl_follows',
  'DROP TABLE IF EXISTS wl_wishlist',
  'DROP TABLE IF EXISTS wl_notifications',
  'DROP TABLE IF EXISTS wl_messages',
  'DROP TABLE IF EXISTS wl_reviews',
  'DROP TABLE IF EXISTS wl_orders',
  'DROP TABLE IF EXISTS wl_proposals',
  'DROP TABLE IF EXISTS wl_projects',
  'DROP TABLE IF EXISTS wl_services',
  'DROP TABLE IF EXISTS wl_documents',
  'DROP TABLE IF EXISTS wl_sessions',
  'DROP TABLE IF EXISTS wl_users',
];

// One statement at a time: the pg driver can't run several statements in one parameterised query.
const run = async (db, statements) => { for (const s of statements) await sql.raw(s).execute(db); };

export const up = db => run(db, UP);
export const down = db => run(db, DOWN);
