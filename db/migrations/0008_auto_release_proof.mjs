/* Automatic payment after the approval period, and proof for reported problems.

   wl_orders.delivered_at: when the freelancer marked the order as delivered (projects and bookings
   got theirs in 0007). Orders delivered before this migration stay NULL: they never pay out by themselves.
   wl_payments.auto_release: the payment was made under Terms that include the automatic payment.
   Earlier payments stay false and keep waiting for the client or an admin.
   wl_payments.reminded_at / problem_reminded_at: the client / the admins were reminded of the deadline.
   wl_payment_proofs: files either side attached to a reported problem. Private, so they're kept here
   like verification documents, not in the photo bucket. `data` is cleared once no longer needed. */
import { sql } from 'kysely';

const UP = [
  'ALTER TABLE wl_orders ADD COLUMN delivered_at timestamptz',
  `ALTER TABLE wl_payments
     ADD COLUMN auto_release boolean NOT NULL DEFAULT false,
     ADD COLUMN reminded_at timestamptz,
     ADD COLUMN problem_reminded_at timestamptz`,
  `CREATE TABLE wl_payment_proofs (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id  integer NOT NULL REFERENCES wl_payments (id) ON DELETE CASCADE,
    user_id     integer NOT NULL REFERENCES wl_users (id) ON DELETE CASCADE,
    file_name   text NOT NULL DEFAULT '',
    mime        text NOT NULL,
    data        bytea,  -- cleared 6 months after the payment was decided
    uploaded_at timestamptz NOT NULL DEFAULT now()
  )`,
  'CREATE INDEX wl_payment_proofs_payment ON wl_payment_proofs (payment_id)',
];

const DOWN = [
  'DROP TABLE IF EXISTS wl_payment_proofs',
  'ALTER TABLE wl_payments DROP COLUMN IF EXISTS problem_reminded_at, DROP COLUMN IF EXISTS reminded_at, DROP COLUMN IF EXISTS auto_release',
  'ALTER TABLE wl_orders DROP COLUMN IF EXISTS delivered_at',
];

const run = async (db, statements) => { for (const s of statements) await sql.raw(s).execute(db); };

export const up = db => run(db, UP);
export const down = db => run(db, DOWN);
